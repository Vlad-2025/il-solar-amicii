"""Regenerate db/schema.sql (Postgres DDL) from db/models.py.

    python scripts/dump_schema.py
Paste the file into Supabase -> SQL editor, or let the app create the tables on first start.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from db.models import metadata  # noqa: E402


def main() -> None:
    parts = ["-- Generated by scripts/dump_schema.py from db/models.py. Do not edit by hand.\n"]
    dialect = postgresql.dialect()
    for table in metadata.sorted_tables:
        ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip()
        parts.append(ddl + ";\n")
        for idx in table.indexes:
            parts.append(str(CreateIndex(idx, if_not_exists=True).compile(dialect=dialect)).strip() + ";\n")
    (ROOT / "db" / "schema.sql").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote db/schema.sql ({len(metadata.sorted_tables)} tables)")


if __name__ == "__main__":
    main()
